use std::collections::BTreeMap;

use serde_json::{Map, Value};

pub(crate) fn generate_cli_help_source(
    option_sets: &Value,
    command_spec: &Value,
) -> Result<String, String> {
    let Value::Object(option_sets) = option_sets else {
        return Err("CLI help spec must be a JSON object".to_string());
    };
    let Value::Object(command_spec) = command_spec else {
        return Err("CLI command spec must be a JSON object".to_string());
    };

    let mut output = String::from("// @generated by build.rs\n\n");
    let rendered_options = render_option_sets(option_sets, command_spec)?;
    generate_command_spec(&mut output, command_spec, &rendered_options)?;
    Ok(output)
}

fn render_option_sets(
    option_sets: &Map<String, Value>,
    command_spec: &Map<String, Value>,
) -> Result<BTreeMap<String, String>, String> {
    let mut rendered_options = option_sets
        .iter()
        .map(|(name, options)| Ok((name.clone(), render_options(options)?)))
        .collect::<Result<BTreeMap<_, _>, String>>()?;
    let combined_options = object_field(command_spec, "combinedOptions")?;
    let mut combined_options = combined_options.iter().collect::<Vec<_>>();
    combined_options.sort_by_key(|(left, _)| *left);
    for (name, parts) in combined_options {
        let Value::Array(parts) = parts else {
            return Err("combined option parts must be an array".to_string());
        };
        let parts = parts
            .iter()
            .map(|part| {
                part.as_str()
                    .ok_or_else(|| "combined option part must be a string".to_string())
            })
            .collect::<Result<Vec<_>, _>>()?;
        let rendered = render_combined_options(&rendered_options, &parts)?;
        rendered_options.insert(name.clone(), rendered);
    }
    Ok(rendered_options)
}

pub(crate) fn render_options(options: &Value) -> Result<String, String> {
    let Value::Array(options) = options else {
        return Err("CLI help option set must be an array".to_string());
    };
    let options = options
        .iter()
        .map(|option| {
            let Value::Object(option) = option else {
                return Err("CLI help option must be an object".to_string());
            };
            Ok(option)
        })
        .collect::<Result<Vec<_>, _>>()?;
    let width = options
        .iter()
        .map(|option| string_field(option, "flags").map(|flags| flags.len()))
        .collect::<Result<Vec<_>, _>>()?
        .into_iter()
        .max()
        .unwrap_or(36)
        .max(36);
    let mut lines = vec!["OPTIONS:".to_string()];
    for option in options {
        let flags = string_field(option, "flags")?;
        let description = string_field(option, "description")?;
        let mut line = format!("  {flags:<width$} {description}");
        let mut details = Vec::new();
        if let Some(default) = optional_string_field(option, "default")? {
            details.push(format!("default: {default}"));
        }
        if let Some(choices) = option.get("choices") {
            let Value::Array(choices) = choices else {
                return Err("CLI help choices must be an array".to_string());
            };
            if !choices.is_empty() {
                let choices = choices
                    .iter()
                    .map(|choice| {
                        choice
                            .as_str()
                            .ok_or_else(|| "CLI help choice must be a string".to_string())
                    })
                    .collect::<Result<Vec<_>, _>>()?;
                details.push(format!("choices: {}", choices.join(" | ")));
            }
        }
        if !details.is_empty() {
            line.push_str(&format!(" ({})", details.join(", ")));
        }
        lines.push(line);
    }
    Ok(lines.join("\n"))
}

fn generate_command_spec(
    output: &mut String,
    command_spec: &Map<String, Value>,
    rendered_options: &BTreeMap<String, String>,
) -> Result<(), String> {
    let root = object_field(command_spec, "root")?;
    output.push_str("const ROOT_USAGE: &[&str] = &");
    output.push_str(&rust_string_slice(array_field(root, "usage")?)?);
    output.push_str(";\n\n");
    output.push_str("const ROOT_COMMANDS: &[(&str, &str)] = &");
    output.push_str(&rust_command_slice(array_field(root, "commands")?)?);
    output.push_str(";\n\n");
    output.push_str("const ROOT_OPTIONS: &str = ");
    output.push_str(&rust_string_literal(option_text(
        rendered_options,
        &string_field(root, "options")?,
    )?)?);
    output.push_str(";\n\n");

    let pages = array_field(command_spec, "pages")?;
    output.push_str("const HELP_PAGES: &[HelpPage] = &[\n");
    for page in pages {
        let Value::Object(page) = page else {
            return Err("help page must be an object".to_string());
        };
        let path = array_field(page, "path")?;
        let description = string_field(page, "description")?;
        let usage = string_field(page, "usage")?;
        let commands = optional_array_field(page, "commands")?;
        let options = optional_string_field(page, "options")?
            .map(|option_set| option_text(rendered_options, &option_set))
            .transpose()?;
        output.push_str("    HelpPage {\n");
        output.push_str("        path: &");
        output.push_str(&rust_string_slice(path)?);
        output.push_str(",\n");
        output.push_str("        description: ");
        output.push_str(&rust_string_literal(&description)?);
        output.push_str(",\n");
        output.push_str("        usage: ");
        output.push_str(&rust_string_literal(&usage)?);
        output.push_str(",\n");
        output.push_str("        options: ");
        match options {
            Some(options) => {
                output.push_str("Some(");
                output.push_str(&rust_string_literal(options)?);
                output.push_str("),\n");
            }
            None => output.push_str("None,\n"),
        }
        output.push_str("        commands: &");
        output.push_str(&rust_command_slice(commands.unwrap_or(&[]))?);
        output.push_str(",\n");
        output.push_str("    },\n");
    }
    output.push_str("];\n");
    Ok(())
}

fn render_combined_options(
    options: &BTreeMap<String, String>,
    parts: &[&str],
) -> Result<String, String> {
    let mut option_lines = Vec::new();
    for part in parts {
        let rendered = options
            .get(*part)
            .ok_or_else(|| format!("missing generated option set {part}"))?;
        option_lines.extend(rendered.lines().skip(1));
    }
    Ok(format!("OPTIONS:\n{}", option_lines.join("\n")))
}

fn option_text<'a>(
    rendered_options: &'a BTreeMap<String, String>,
    option_set: &str,
) -> Result<&'a str, String> {
    rendered_options
        .get(option_set)
        .map(String::as_str)
        .ok_or_else(|| format!("missing option set {option_set}"))
}

fn object_field<'a>(
    object: &'a Map<String, Value>,
    field: &str,
) -> Result<&'a Map<String, Value>, String> {
    let Some(Value::Object(value)) = object.get(field) else {
        return Err(format!("missing CLI help object field {field}"));
    };
    Ok(value)
}

fn array_field<'a>(object: &'a Map<String, Value>, field: &str) -> Result<&'a [Value], String> {
    let Some(Value::Array(value)) = object.get(field) else {
        return Err(format!("missing CLI help array field {field}"));
    };
    Ok(value)
}

fn optional_array_field<'a>(
    object: &'a Map<String, Value>,
    field: &str,
) -> Result<Option<&'a [Value]>, String> {
    object
        .get(field)
        .map(|value| {
            let Value::Array(value) = value else {
                return Err(format!("CLI help field {field} must be an array"));
            };
            Ok(value.as_slice())
        })
        .transpose()
}

fn string_field(object: &Map<String, Value>, field: &str) -> Result<String, String> {
    optional_string_field(object, field)?.ok_or_else(|| format!("missing CLI help field {field}"))
}

fn optional_string_field(
    object: &Map<String, Value>,
    field: &str,
) -> Result<Option<String>, String> {
    object
        .get(field)
        .map(|value| {
            value
                .as_str()
                .map(str::to_string)
                .ok_or_else(|| format!("CLI help field {field} must be a string"))
        })
        .transpose()
}

fn rust_string_slice(values: &[Value]) -> Result<String, String> {
    let values = values
        .iter()
        .map(|value| {
            value
                .as_str()
                .ok_or_else(|| "CLI help string array item must be a string".to_string())
                .and_then(rust_string_literal)
        })
        .collect::<Result<Vec<_>, _>>()?
        .join(", ");
    Ok(format!("[{values}]"))
}

fn rust_command_slice(values: &[Value]) -> Result<String, String> {
    let values = values
        .iter()
        .map(|value| {
            let Value::Object(value) = value else {
                return Err("CLI help command item must be an object".to_string());
            };
            Ok(format!(
                "({}, {})",
                rust_string_literal(&string_field(value, "name")?)?,
                rust_string_literal(&string_field(value, "description")?)?
            ))
        })
        .collect::<Result<Vec<_>, _>>()?
        .join(", ");
    Ok(format!("[{values}]"))
}

fn rust_string_literal(value: &str) -> Result<String, String> {
    serde_json::to_string(value).map_err(|error| format!("encode Rust string literal: {error}"))
}

#[cfg(test)]
mod tests {
    use serde_json::json;

    use super::*;

    #[test]
    fn generates_combined_option_text_from_data() {
        let option_sets = json!({
            "agent_options": [
                {
                    "flags": "--json",
                    "description": "Output in JSON format"
                }
            ],
            "session_options": [
                {
                    "flags": "-i, --id <ID>",
                    "description": "Show a specific session"
                }
            ]
        });
        let command_spec = json!({
            "combinedOptions": {
                "agent_session_options": ["agent_options", "session_options"]
            },
            "root": {
                "usage": ["ccusage <COMMANDS>"],
                "options": "agent_options",
                "commands": [
                    {
                        "name": "session",
                        "description": "Show usage grouped by session"
                    }
                ]
            },
            "pages": [
                {
                    "path": ["session"],
                    "description": "Show usage grouped by session",
                    "usage": "ccusage session <OPTIONS>",
                    "options": "agent_session_options"
                }
            ]
        });

        let output = generate_cli_help_source(&option_sets, &command_spec).unwrap();

        assert!(!output.contains("fn "));
        assert!(output.contains("options: Some(\"OPTIONS:\\n  --json"));
        assert!(output.contains("-i, --id <ID>"));
    }

    #[test]
    fn generates_command_help_pages_from_data() {
        let option_sets = json!({
            "agent_options": [
                {
                    "flags": "--json",
                    "description": "Output in JSON format"
                }
            ]
        });
        let command_spec = json!({
            "combinedOptions": {},
            "root": {
                "usage": ["ccusage <COMMANDS>"],
                "options": "agent_options",
                "commands": [
                    {
                        "name": "agent",
                        "description": "Show agent usage commands"
                    }
                ]
            },
            "pages": [
                {
                    "path": ["agent"],
                    "description": "Usage reports for agent.",
                    "usage": "ccusage agent <COMMANDS>",
                    "commands": [
                        {
                            "name": "daily",
                            "description": "Show usage by day"
                        }
                    ]
                },
                {
                    "path": ["agent", "daily"],
                    "description": "Show usage by day",
                    "usage": "ccusage agent daily <OPTIONS>",
                    "options": "agent_options"
                }
            ]
        });

        let output = generate_cli_help_source(&option_sets, &command_spec).unwrap();

        assert!(output.contains("const ROOT_COMMANDS"));
        assert!(output.contains("path: &[\"agent\"]"));
        assert!(output.contains("path: &[\"agent\", \"daily\"]"));
        assert!(output.contains("commands: &[(\"daily\", \"Show usage by day\")]"));
    }

    #[test]
    fn renders_defaults_and_choices_in_option_details() {
        let options = json!([
            {
                "flags": "--mode <MODE>",
                "description": "Cost calculation mode",
                "default": "auto",
                "choices": ["auto", "calculate", "display"]
            }
        ]);

        let output = render_options(&options).unwrap();

        assert!(output.contains("default: auto"));
        assert!(output.contains("choices: auto | calculate | display"));
    }
}
